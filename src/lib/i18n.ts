const DICTS: Record<Locale, Dict> = { en: EN, ar: AR, fr: FR };

type Ctx = { locale: Locale; setLocale: (l: Locale) => void; t: (k: string) => string; dir: "ltr" | "rtl" };

const I18nCtx = createContext<Ctx>({
  locale: "en",
  setLocale: () => {},
  t: (k) => EN[k] ?? k,
  dir: "ltr",
});

const STORAGE_KEY = "carmel.locale";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
      if (saved && (saved === "en" || saved === "ar" || saved === "fr")) {
        setLocaleState(saved);
      }
    } catch {
      /* ignore */
    }
  }, []);

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.setAttribute("lang", locale);
    document.documentElement.setAttribute("dir", locale === "ar" ? "rtl" : "ltr");
  }, [locale]);

  const setLocale = (l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  };

  const t = (k: string) => DICTS[locale][k] ?? EN[k] ?? k;
  const dir: "ltr" | "rtl" = locale === "ar" ? "rtl" : "ltr";

  return createElement(I18nCtx.Provider, { value: { locale, setLocale, t, dir } }, children);
}

export function useI18n() {
  return useContext(I18nCtx);
}

export const STAGE_GROUPS = ["primary_1_2", "primary_3_6", "preparatory", "secondary"] as const;
export const GRADES_BY_STAGE: Record<(typeof STAGE_GROUPS)[number], string[]> = {
  primary_1_2: ["p1", "p2"],
  primary_3_6: ["p3", "p4", "p5", "p6"],
  preparatory: ["prep1", "prep2", "prep3"],
  secondary: ["sec1", "sec2", "sec3"],
};

// Simplified stage picker for signup: student picks Primary/Preparatory/Secondary,
// then a specific grade. Primary 1–6 spans two stage groups.
export function stageGroupForGrade(grade: string): (typeof STAGE_GROUPS)[number] {
  if (grade === "p1" || grade === "p2") return "primary_1_2";
  if (grade === "p3" || grade === "p4" || grade === "p5" || grade === "p6") return "primary_3_6";
  if (grade === "prep1" || grade === "prep2" || grade === "prep3") return "preparatory";
  return "secondary";
}
